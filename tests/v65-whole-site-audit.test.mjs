import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const root=new URL("../",import.meta.url);
const read=p=>readFileSync(new URL(p,root),"utf8");
const html=read("index.html"),css=read("styles-v5.css");
const entry=read("scripts/v5-cinematic.js");
const engine=read("scripts/v6-three.src.mjs");
const glb=read("scripts/v62-glb-loader.src.mjs");
const gpu=read("scripts/v6-gpu-browser-audit.mjs");
test("V6.5 page opens with original high-quality WebP on all devices",()=>{
 assert.match(read("prime.html"),/class="v6-static-fallback"/);
 assert.doesNotMatch(html,/v5-cinematic-mobile\.webp/);
 assert.doesNotMatch(html,/class="v5-stage-render"/);
 assert.match(html,/class="v65-load-status" role="status" aria-live="polite"/);
 assert.match(css,/\[data-v6-state="preparing"\] \.v6-three-mount/);
 assert.match(css,/\[data-v6-state="active"\] \.v6-three-mount/);
 assert.match(entry,/if\(threeStart\)threeStart.hidden=false/);
 assert.doesNotMatch(entry,/trigger3D\.observe/);
 assert.match(gpu,/Desktop loads WebGL without a user click/);
});
test("V6.5 GLB boot is transactional and scene becomes visible only after a GPU frame",()=>{
 assert.match(glb,/Promise\.allSettled\(tasks\)/);
 assert.match(glb,/Promise\.race\(/);
 assert.match(glb,/setTimeout\(\(\)=>resolve\(timeoutToken\),10000\)/);
 assert.match(glb,/clearTimeout\(deadline\)/);
 assert.match(glb,/if\(outcomes===timeoutToken\)/);
 assert.match(glb,/disposeLoaded\(item\.value\.gltf\)/);
 assert.match(glb,/sceneParents=new Map/);
 assert.match(engine,/stage\.dataset\.v6State="preparing"/);
 assert.match(engine,/const revealReady=\(\)=>/);
 assert.match(engine,/renderer\.render\(scene,camera\);\s*controls\.hidden=false;\s*stage\.dataset\.v6State="active"/);
 assert.match(engine,/stage\.dispatchEvent\(new Event\("desset:v6-ready"\)\)/);
 assert.match(engine,/stage\.dispatchEvent\(new Event\("desset:v6-unavailable"\)\)/);
 assert.match(entry,/stage\.addEventListener\("desset:v6-ready"/);
 assert.match(entry,/stage\.addEventListener\("desset:v6-unavailable"/);
 assert.match(entry,/runRequestedTour\(\)/);
});
test("V6.5 tablet scene uses desktop geometry with low-cost GPU settings and safe resize",()=>{
 assert.match(engine,/const coarse=window\.matchMedia\?\.\("\(max-width: 800px\)"\)/);
 assert.match(engine,/const vertical=window\.matchMedia\?\.\("\(max-width: 430px\)"\)/);
 assert.match(engine,/const presets=vertical\?/);
 assert.match(engine,/const path=vertical\?/);
 assert.match(engine,/renderer\.shadowMap\.enabled=!coarse/);
 assert.match(engine,/isVertical!==vertical\|\|isCoarse!==coarse/);
 assert.match(gpu,/Tablet camera fits all three GLB models within the landscape frame/);
 assert.match(gpu,/Resize across quality breakpoint frees GPU and offers safe reopen/);
 assert.match(css,/grid-template-columns:repeat\(4,minmax\(0,1fr\)\)/);
 assert.match(css,/min-height:44px/);
});
