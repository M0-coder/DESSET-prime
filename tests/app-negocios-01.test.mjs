import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {createHash} from "node:crypto";
import {assertClosedAppPage} from "../scripts/app-distribution-contract.mjs";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
for(const dir of ["","dist/"])test("APP-NEGOCIOS-01 owner-approved five profiles, yellow icon and closed distribution "+(dir||"source"),()=>{
 const h=read(dir+"aplicaciones-comercios.html");
 assertClosedAppPage(h,"aplicaciones-comercios");
 assert.match(h,/<body class="desset-consumer desset-merchant">/);
 assert.match(h,/<title>DESSET Negocios<\/title>/);
 assert.match(h,/Tu negocio, en una aplicación\./);
 assert.match(h,/Vende productos, ofrece servicios y conecta con nuevos clientes\./);
 assert.match(h,/data-app-role="comercios"/);
 assert.equal((h.match(/<button[^>]* disabled>/g)||[]).length,3);
 assert.deepEqual([...h.matchAll(/<div class="consumer-category">[\s\S]*?<span>([^<]+)<\/span><\/div>/g)].map(m=>m[1]),["Comerciantes","Vendedores","Conductores","Anfitriones","Proveedores"]);
 const desktop=h.match(/<button class="consumer-web" type="button" disabled>([\s\S]*?)<\/button>/)?.[1];
 assert.ok(desktop);assert.equal((desktop.match(/<svg\b/g)||[]).length,1);assert.match(desktop,/<span>Desktop<\/span>$/);
 assert.match(h,/data-app-activation>No habilitada/);assert.match(h,/data-app-coverage>No confirmada/);
 assert.match(h,/No compartas documentos, claves ni datos bancarios/);
 assert.match(h,/src="\.\/assets\/desset-negocios-app-icon\.svg"/);
 const svg=read(dir+"assets/desset-negocios-app-icon.svg");
 assert.equal(createHash("sha256").update(svg).digest("hex"),"2c8def4089ff6251bf5ff1de9b514881a5a135b250d4a34f038cd56b1baca67f");
 assert.equal(svg,read(dir+"assets/desset-app-icon.svg").replace('fill="#FF3328"','fill="#FFC62F"'));
 const directory=read(dir+"aplicaciones.html");
 assert.match(directory,/<a class="apps-icon apps-icon-business apps-icon-negocios" href="\.\/aplicaciones-comercios\.html" aria-label="DESSET Negocios" data-app-role="comercios"><img src="\.\/assets\/desset-negocios-app-icon\.svg"/);
 const css=read(dir+"styles-applications.css");
 assert.ok(css.includes(".desset-merchant .apps-page.consumer-compact .consumer-accesses .consumer-web{background:#FFC62F;color:#000000}"));
 assert.ok(css.includes(".desset-merchant .consumer-compact .consumer-category svg{color:#916500}"));
 assert.ok(!read(dir+"aplicaciones-clientes.html").includes("desset-negocios-app-icon.svg"));
 assert.ok(!read(dir+"aplicaciones-repartidores.html").includes("desset-negocios-app-icon.svg"));
});
